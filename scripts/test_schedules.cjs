const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..', 'prototype');
const context = { window: {}, structuredClone, setTimeout: () => 0, clearTimeout() {}, localStorage: { getItem: () => null } };
vm.createContext(context);
for (const file of ['data.js', 'js/i18n.js', 'js/core.js', 'js/schedules.js']) vm.runInContext(fs.readFileSync(path.join(root, file), 'utf8'), context, { filename: file });
const A = context.window.App;
const spring = { season: 'spring', day: 10, weather: 'sun', time: 1200 };
const vincent = A.D.schedules['文森特'].groups.find(g => /每个季节9日和23日/.test(g.label));
assert(vincent, 'Archived Vincent clinic dates must be present');
assert.equal(A.schedules.matches(vincent, spring), false, 'A clinic visit on the ninth must not match the tenth');
assert.equal(A.schedules.matches(vincent, { ...spring, day: 9 }), true);
const george = A.D.schedules['乔治'].groups.find(g => /每个季节.*23日/.test(g.label));
assert(george);
assert.equal(A.schedules.matches(george, { ...spring, day: 9 }), false, 'A matching weekday must not override the fixed date');
assert.equal(A.schedules.matches(george, { ...spring, day: 23 }), true);
const evelyn = A.D.schedules['艾芙琳'].groups.find(g => /每个季节.*第2天/.test(g.label));
assert(evelyn);
assert.equal(A.schedules.matches(evelyn, { ...spring, day: 9 }), false);
assert.equal(A.schedules.matches({ label: '不下雨的星期六' }, { ...spring, day: 6 }), true);
assert.equal(A.schedules.matches({ label: '不下雨的星期六' }, { ...spring, day: 6, weather: 'rain' }), false);
assert.equal(A.schedules.matches({ label: '日常时间表（星期五除外）' }, spring), null, 'Unparsed exclusion conditions must stay conditional');
assert.equal(A.schedules.matches({ label: '春季4日' }, { ...spring, season: 'fall', day: 4 }), false);
console.log('Schedule condition checks passed: recurring clinic dates, weekdays, weather, season and unknown exclusions.');

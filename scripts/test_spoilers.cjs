// 无依赖回归测试：使用真实快照，验证展示权限与游戏可达条件相互独立。
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..', 'prototype');
function boot(saved) {
  const ctx = { window: {}, structuredClone, setTimeout: () => 0, clearTimeout() {}, localStorage: { getItem: () => saved || null } };
  vm.createContext(ctx);
  for (const file of ['data.js', 'js/core.js', 'js/tree.js', 'js/spoilers.js']) vm.runInContext(fs.readFileSync(path.join(root, file), 'utf8'), ctx, { filename: file });
  return ctx.window.App;
}
const A = boot(), S = A.spoilers;
const ref = id => ({ type: 'page', id });
assert.equal(A.itemInfo('(O)book animalcatalogue').id, '(O)Book_AnimalCatalogue', '保留旧编号的查阅兼容性');
assert.equal(S.active(), true);
assert.equal(A.state.preset, 'unknown', '首次访问不应假定示例进度为真实探索进度');
for (const name of ['木材', '石头', '煤炭', '铁锭', '阿比盖尔', '鱼店', '鲶鱼', '钓鱼', '烹饪']) assert.equal(S.canView(ref(name)), true, `普通查询应可用：${name}`);
for (const name of ['姜岛', '雷欧', '科罗布斯', '齐先生', '齐豆', '齐瓜', '秘密森林', '头骨钥匙', '完美']) assert.equal(S.canView(ref(name)), false, `默认保护：${name}`);
// 地点共享坐标或相邻，不应互相继承隐藏状态。
assert.equal(S.mapPoint({ type: 'location', id: 'Joja超市' }, [297, 99, 'valley']), true);
assert.equal(S.mapPoint({ type: 'location', id: '电影院' }, [297, 99, 'valley']), false);
assert.equal(S.mapPoint({ type: 'location', id: '社区中心' }, [237, 71, 'valley']), true);
assert.equal(S.mapPoint({ type: 'location', id: 'Joja仓库' }, [237, 71, 'valley']), false);
assert.equal(S.mapPoint({ type: 'location', id: '探险家公会' }, [303, 40, 'valley']), true, '附近入口受保护不能隐藏普通地点');
assert.equal(S.area('mines'), false);
assert.equal(S.mapPoint({ type: 'fish', id: '鲶鱼' }, [130, 160, 'valley']), true, '普通河流标记保持可读');
assert.equal(S.mapPoint({ type: 'fish', id: '鲶鱼' }, [20, 110, 'valley']), false, '同一种鱼在未探索地区的标记继续保护');
assert.equal(S.mapPoint({ type: 'fish', id: '鲤鱼' }, [280, 53, 'valley']), true, '普通湖泊不被附近地点的隐藏半径影响');
assert.equal(S.mapPoint({ type: 'fish', id: '鲤鱼' }, [134, 194, 'valley']), false);
assert.equal(S.mapPoint({ type: 'fish', id: '鲤鱼' }, [114, 201, 'valley']), false, '校准后的内部地点入口保持保护');
assert.equal(S.mapPoint({ type: 'fish', id: '鲶鱼' }, [138, 165, 'valley']), true, '校准后的森林河流保持可读');
assert.equal(S.mapPoint({ type: 'fish', id: '鬼鱼' }, [275, 40, 'valley']), false, '双地图解析补回的内部鱼类坐标不能越过保护');
A.setProgress(p => { p.tools.斧头 = 2; });
assert.equal(A.areaState('secret_woods').state, 'open');
assert.equal(S.area('secret_woods'), false, '具备进入能力不等于已探索');
S.reveal({ type: 'area', id: 'ginger_island' });
assert.equal(S.canView(ref('姜岛')), true);
for (const name of ['雷欧', '姜岛商人', '齐先生的核桃房']) assert.equal(S.canView(ref(name)), false, `单条展开不能扩大范围：${name}`);
assert.equal(A.state.spoilers.known.length, 0, '临时查看不得写入已知内容');
assert.equal(boot(JSON.stringify(A.state)).spoilers.area('ginger_island'), false, '刷新后临时展开重置');
S.reveal(ref('秘密森林'), true);
assert.equal(S.mapPoint({ type: 'fish', id: '鲤鱼' }, [20, 110, 'valley']), true, '确认地点后只展开对应标记');
assert.equal(S.mapPoint({ type: 'fish', id: '鲤鱼' }, [134, 194, 'valley']), false, '确认一个地点不会展开另一地点');
assert.equal(boot(JSON.stringify(A.state)).spoilers.area('secret_woods'), true, '主动确认可以跨刷新保留');
assert.equal(S.textAllowed('可在鱼店购买，后续还可以向科罗布斯购买。'), false, '普通条目中的其他途径仍须保护');
S.reveal(ref('姜岛商人'));
assert.equal(S.textAllowed('姜岛商人', '姜岛商人'), true, '已主动查看的标题可以出现');
S.setEnabled(false);
assert.equal(S.canView(ref('齐先生')), true);
assert.equal(boot(JSON.stringify(A.state)).spoilers.active(), false, '全局偏好可以保存');
S.setEnabled(true);
assert.equal(S.canView(ref('齐先生')), false);
assert.equal(S.area('ginger_island'), false, '重新保护时收起临时展开');
assert.equal(S.area('secret_woods'), true, '明确标记的已知内容仍可查看');
A.applyPreset('fresh');
assert.equal(S.area('secret_woods'), false, '切换存档预设重置已知内容');
const migrated = JSON.parse(JSON.stringify(A.state)); delete migrated.spoilers;
assert.equal(boot(JSON.stringify(migrated)).spoilers.active(), true, '旧存储默认启用保护');
console.log('防剧透回归通过：普通查询、未知进度、可达与探索分离、单条范围、持久化、重置与旧状态迁移。');
